# --- router/index.js ---
 $routerIndex = @'
import { createRouter, createWebHistory } from 'vue-router'
import routes from './routes'

const router = createRouter({
  history: createWebHistory(),
  routes,
  scrollBehavior(to, from, savedPosition) {
    if (savedPosition) return savedPosition
    if (to.hash) return { el: to.hash, behavior: 'smooth' }
    return { top: 0 }
  },
})

router.beforeEach((to, from, next) => {
  const isLoggedIn = !!(window.Laravel && window.Laravel.user)
  if (to.meta.requiresAuth && !isLoggedIn && to.name !== 'login') {
    next({ name: 'login' })
  } else {
    next()
  }
})

router.afterEach((to) => {
  const title = to.meta.title || to.name
  document.title = title ? title + ' - Advaca' : 'Advaca'
})

export default router
'@
Set-Content -Path "$routerDir\index.js" -Value $routerIndex -Encoding UTF8
Write-Host "[OK] Created router/index.js" -ForegroundColor Green

# --- router/routes.js (auto-generated from all .vue pages) ---
 $pagesRoot = "$root\resources\js\views\Pages"
if (-not (Test-Path $pagesRoot)) {
    Write-Host "[ERROR] Pages folder missing: $pagesRoot" -ForegroundColor Red
    exit 1
}

 $files = Get-ChildItem -Path $pagesRoot -Recurse -Filter *.vue

 $lines = @()
 $lines += "// AUTO-GENERATED by fix-advaca.ps1 - safe to edit manually"
 $lines += "import HomeLayout from '../views/Layouts/Empty.vue'"
 $lines += ""
 $lines += "const routes = ["
 $lines += "  { path: '/', name: 'home', component: HomeLayout, meta: { requiresAuth: false } },"

foreach ($f in $files) {
    $rel  = $f.FullName.Substring($pagesRoot.Length).TrimStart('\').Replace('\','/')
    $dir  = Split-Path $rel -Parent
    $name = $f.BaseName
    $cleanDir = $dir.ToLower()
    $importPath = '../views/Pages/' + $rel

    if ($name -eq 'Index') {
        if ($cleanDir -eq '') { continue }
        $url  = '/' + $cleanDir
        $rn   = $cleanDir + '.index'
        $lines += "  { path: '$url', name: '$rn', component: () => import('$importPath'), meta: { requiresAuth: true } },"
    }
    elseif ($name -eq 'Action') {
        if ($cleanDir -eq '') { continue }
        $createUrl = '/' + $cleanDir + '/create'
        $editUrl   = '/' + $cleanDir + '/:id/edit'
        $createRn  = $cleanDir + '.create'
        $editRn    = $cleanDir + '.edit'
        $lines += "  { path: '$createUrl', name: '$createRn', component: () => import('$importPath'), meta: { requiresAuth: true } },"
        $lines += "  { path: '$editUrl',   name: '$editRn',   component: () => import('$importPath'), meta: { requiresAuth: true } },"
    }
    elseif ($name -eq 'Show') {
        if ($cleanDir -eq '') { continue }
        $url = '/' + $cleanDir + '/:id'
        $rn  = $cleanDir + '.show'
        $lines += "  { path: '$url', name: '$rn', component: () => import('$importPath'), meta: { requiresAuth: true } },"
    }
    else {
        $slug = $name.ToLower()
        if ($cleanDir -eq '') {
            $url = '/' + $slug
            $rn  = $slug
        } else {
            $url = '/' + $cleanDir + '/' + $slug
            $rn  = $cleanDir + '.' + $slug
        }
        $lines += "  { path: '$url', name: '$rn', component: () => import('$importPath'), meta: { requiresAuth: true } },"
    }
}

 $lines += "]"
 $lines += ""
 $lines += "export default routes"

Set-Content -Path "$routerDir\routes.js" -Value $lines -Encoding UTF8
Write-Host "[OK] Generated router/routes.js with $($files.Count) page routes" -ForegroundColor Green

