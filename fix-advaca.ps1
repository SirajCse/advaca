Write-Host ""
Write-Host "==== Step 5: Convert all 812 pages (Inertia -> vue-router) ====" -ForegroundColor Cyan

 $pages = Get-ChildItem -Path $pagesRoot -Recurse -Filter *.vue
 $count = 0

foreach ($f in $pages) {
    $c = Get-Content $f.FullName -Raw -Encoding UTF8
    $orig = $c

    # Replace imports - Link -> RouterLink alias
    $c = $c -replace "import\s+\{\s*Head\s*,\s*Link\s*,?\s*([^}]+)\}\s+from\s+['`"]@inertiajs/vue3['`"]", "import { RouterLink as Link } from 'vue-router'"
    $c = $c -replace "import\s+\{\s*Link\s*,\s*Head\s*,?\s*([^}]+)\}\s+from\s+['`"]@inertiajs/vue3['`"]", "import { RouterLink as Link } from 'vue-router'"
    $c = $c -replace "import\s+\{\s*Head\s*,\s*Link\s*\}\s+from\s+['`"]@inertiajs/vue3['`"]", "import { RouterLink as Link } from 'vue-router'"
    $c = $c -replace "import\s+\{\s*Link\s*,\s*Head\s*\}\s+from\s+['`"]@inertiajs/vue3['`"]", "import { RouterLink as Link } from 'vue-router'"
    $c = $c -replace "import\s+\{\s*Link\s*\}\s+from\s+['`"]@inertiajs/vue3['`"]", "import { RouterLink as Link } from 'vue-router'"

    # Drop bare Head imports (no vue-router equivalent needed; Vue's built-in <title> works)
    $c = $c -replace "import\s+\{\s*Head\s*\}\s+from\s+['`"]@inertiajs/vue3['`"];?\s*\r?\n", ""

    # Link href -> to (RouterLink uses `to`)
    $c = $c -replace '<Link\s+href="', '<Link to="'
    $c = $c -replace '<Link\s+:href="', '<Link :to="'

    if ($c -ne $orig) {
        Set-Content -Path $f.FullName -Value $c -NoNewline -Encoding UTF8
        $count++
    }
}
Write-Host "[OK] Converted $count of $($files.Count) pages" -ForegroundColor Green

